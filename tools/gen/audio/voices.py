def v_dj_nova(kind, n, rng):
    """FM bleeps. Two-operator FM at a 1:1 ratio (a brassy, harmonic 'synth lead', NOT the inharmonic
    ratios that would make a bell and collide with Vela), an index that decays from bright to mellow in
    60 ms (the 'bwow'), and a deep 7 Hz wah - the club 'wub' - on top. Hype: big interval jumps, punchy
    attacks, two bleeps where anyone else has one gesture. The first build also dropped 5 semitones on
    every attack (a laser 'zap'); measured, that made Nova the closest voice to Pop, whose whole identity
    is the DOWNWARD sweep, so the attack now only settles 1 semitone and the wah carries Nova instead."""
    # "!" is ONE big bleep that bends up 5 semitones ("bwoop!"): round 1's two bleeps 91 ms apart were
    # an 11/s burst, babble-rate. Every two-bleep gesture here has its bleeps >= 150 ms apart.
    spec = {"short": [(0.0, 1.0, 0, 3.0, 0.0)],
            "long": [(0.0, 0.42, 0, 3.0, 0.0), (0.44, 1.0, 5, 3.4, 0.0)],
            "ask": [(0.0, 0.42, 0, 3.0, 0.0), (0.44, 1.0, 3, 3.0, 5.0)],
            "exclaim": [(0.0, 1.0, 7, 5.0, 5.0)],
            "trail": [(0.0, 0.40, 0, 3.0, 0.0), (0.42, 1.0, -3, 2.0, -5.0)]}[kind]
    y = np.zeros(n)
    for a, b, semis, index, bend in spec:
        s0, s1 = int(a * n), int(b * n)
        m = s1 - s0
        t = S.times(m)
        fc = 370.0 * 2.0 ** (semis / 12.0)
        f = fc * 2.0 ** ((1.0 * np.exp(-t / 0.012) + bend * np.clip(t / (m / S.SR), 0, 1) ** 1.3) / 12.0)
        ph = _phase(f)
        idx = index * np.exp(-t / 0.06) + 0.6
        tone = np.sin(ph + idx * np.sin(ph))
        env = np.minimum(np.clip(t / 0.004, 0, 1), np.exp(-t / 0.12)) * np.clip((m / S.SR - t) / 0.025, 0, 1)
        y[s0:s1] += tone * env
    t = S.times(n)
    # wah 800 Hz +- 1.2 octaves (tops out at 1.84 kHz): at 900 Hz +- 1.4 it reached 2.4 kHz and put 16 %
    # of voice_dj_nova_long's energy above 2 kHz, the most of any file in the cast.
    wob = 800.0 * 2.0 ** (1.2 * np.sin(TWO_PI * (7.0 if kind != "trail" else 4.5) * t))
    wah = S.svf_tv(y, wob, 3.0, "bp")
    return (0.35 * y + 1.1 * wah) * _env(kind, n, 0.004, 0.03)


VOWELS = {
    "mm": (280.0, 1000.0, 2400.0), "u": (330.0, 780.0, 2300.0), "o": (500.0, 900.0, 2500.0),
    "ah": (720.0, 1150.0, 2500.0), "a": (820.0, 1300.0, 2600.0), "er": (550.0, 1400.0, 2400.0),
    "e": (500.0, 1750.0, 2600.0), "i": (350.0, 2200.0, 2900.0),
}


def _formants(src, seq, n, qs=(6.0, 8.0, 10.0), weights=(1.0, 0.6, 0.25), scale=1.0):
    """Run `src` through three gliding formant band-passes following [(t_frac, vowel), ...].
    `scale` multiplies every formant (a smaller vocal tract has proportionally higher formants)."""
    out = np.zeros(n)
    for j in range(3):
        fc = scale * _path([(p, VOWELS[v][j]) for p, v in seq], n)
        out += weights[j] * S.svf_tv(src, fc, qs[j], "bp")
    return out


