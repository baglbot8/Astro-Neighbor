# The user's 2026-09-10 decision (see the UPDATE note in the module docstring): everyone except Zorp
# drops their unique comms voice AND the radio click/static framing, and gets ONE shared, neutral,
# non-vocal "doot" instead - just a tone timed to the letters, nothing that reads as a character or as
# speech. A doot is explicitly NOT animalese: animalese is pitched speech-like syllables built from
# vowel-formant filters (see _formants() / VOWELS above, used by mayor_orbit/stella); a doot has no
# formant filter anywhere in its signal path and no vowel colour - it is one plain oscillator (plus, for
# flavour C, one short click) shaped by an amplitude envelope. Three flavours were built for the user to
# choose from; only flavour A ships (see doot_names() / SHIPPED_VOICE_NAMES below).
DOOT_BASE_HZ = 560.0                    # a plain, neutral pitch - not tuned to register like any CAST voice
# +-3 % pre-baked pitch variants of the SHIPPED flavour (A), so AudioManager can rotate between them and
# a ten-line conversation never plays the identical sample back to back ("machine-gun" repetition).
DOOT_PITCH_MULTS = [0.97, 1.0, 1.03, 1.015]
DOOT_RMS_DB = -20.0                     # target file RMS - well under old voice_robot_*.wav (~-6.9 dBFS
                                        # measured), so ten lines of doots never tire the ear (see report)
DOOT_PEAK_DB = PEAK_CEIL_DB


def render_doot(flavour, pitch_mult=1.0, rng=None):
    """One ~50-80 ms doot buffer at S.SR (not yet resampled/leveled - see _finish_doot).

    flavour "a" (SHIPPED): a soft rounded sine with a tiny downward pitch-drop envelope (glides down
      ~0.7 semitone, ~4 %, over the note) - one pure tone plus a faint (8 %) second harmonic for
      roundness, no formants, no vowel colour.
    flavour "b" (scratch demo only): a warmer triangle / soft-square "boop", a fourth lower than A.
    flavour "c" (scratch demo only): a very short muted "tik-doo" - a soft filtered click attack
      followed by a brief, quiet, heavily lowpassed tone.
    """
    if flavour == "a":
        dur = 0.065
        n = S.n_samples(dur)
        t = S.times(n)
        drop = 2.0 ** (-0.7 * np.clip(t / dur, 0.0, 1.0) / 12.0)      # glides down ~4 % over the note
        f = DOOT_BASE_HZ * pitch_mult * drop
        y = S.sine(f, n) + 0.08 * S.sine(2.0 * f, n)
        env = np.minimum(0.5 - 0.5 * np.cos(math.pi * np.clip(t / 0.008, 0.0, 1.0)),
                          0.5 - 0.5 * np.cos(math.pi * np.clip((dur - t) / 0.026, 0.0, 1.0)))
        return S.lowpass(y * env, 2600.0)
    if flavour == "b":
        dur = 0.075
        n = S.n_samples(dur)
        t = S.times(n)
        f = np.full(n, DOOT_BASE_HZ * 0.79 * pitch_mult)              # a fourth lower: warmer register
        y = 0.8 * S.triangle(f, n) + 0.2 * np.tanh(1.6 * S.pulse(f, n, 0.5))
        env = np.minimum(0.5 - 0.5 * np.cos(math.pi * np.clip(t / 0.01, 0.0, 1.0)),
                          0.5 - 0.5 * np.cos(math.pi * np.clip((dur - t) / 0.03, 0.0, 1.0)))
        return S.lowpass(y * env, 1800.0)
    if flavour == "c":
        dur = 0.07
        n = S.n_samples(dur)
        rng = rng or np.random.default_rng(4200)
        click_n = S.n_samples(0.006)
        click = S.bandpass(rng.uniform(-1.0, 1.0, click_n), 1300.0, 1.0)
        click *= np.exp(-S.times(click_n) / 0.0015)
        tone_n = n - click_n
        tt = S.times(tone_n)
        f = np.full(tone_n, DOOT_BASE_HZ * 0.86 * pitch_mult)
        tone_env = (0.5 - 0.5 * np.cos(math.pi * np.clip(tt / 0.006, 0.0, 1.0))) * np.exp(-tt / 0.028) * 0.55
        tone = S.lowpass(S.sine(f, tone_n) * tone_env, 1400.0)        # muted: heavy lowpass, quiet
        y = np.zeros(n)
        y[:click_n] += click * 0.5
        y[click_n:] += tone
        return y
    raise ValueError(flavour)


def _finish_doot(y, rms_db=DOOT_RMS_DB, peak_db=DOOT_PEAK_DB):
    """fade/DC-clean -> RMS-normalise (gentle, per the user's mix note) -> peak-cap -> COMMS_RATE."""
    y = S.fade_edges(y, 0.002, 0.006)
    y = S.remove_dc(y)
    cur = S.rms(y)
    if cur > 1e-9:
        y = y * (S.db(rms_db) / cur)
    if S.peak(y) > S.db(peak_db):
        y = S.normalize(y, peak_db)
    return S.resample_half(y)


