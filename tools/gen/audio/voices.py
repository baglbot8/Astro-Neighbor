def v_mayor_orbit(kind, n, rng):
    """Square-wave vocoder. A 118 Hz pulse buzz (the machine) through three formant filters that GLIDE
    slowly between vowels (the speech) - one smooth 'mm-oh-ah' per gesture, never a vowel per syllable.
    Pitch is a robot's stepped monotone: the contour is flattened to half depth and quantised to whole
    semitones, with only a slow old-man 4.2 Hz waver on top. Stately, fond, a little creaky."""
    t = S.times(n)
    semis = np.round(0.5 * _path(CONTOUR[kind], n))                      # half depth, whole-semitone steps
    ker = np.hanning(S.n_samples(0.02))
    semis = np.convolve(np.pad(semis, len(ker) // 2, mode="edge"), ker / ker.sum(), mode="same")[len(ker) // 2:len(ker) // 2 + n]
    f = 118.0 * 2.0 ** (semis / 12.0) * 2.0 ** (10.0 * np.sin(TWO_PI * 4.2 * t) / 1200.0)
    src = S.pulse(f, n, 0.4) + 0.3 * S.saw(f * 1.003, n)
    seq = {"short": [(0.0, "mm"), (0.35, "o"), (1.0, "ah")],
           "long": [(0.0, "mm"), (0.25, "o"), (0.6, "ah"), (1.0, "er")],
           "ask": [(0.0, "mm"), (0.4, "ah"), (1.0, "e")],
           "exclaim": [(0.0, "ah"), (0.4, "a"), (1.0, "ah")],
           "trail": [(0.0, "o"), (0.5, "u"), (1.0, "mm")]}[kind]
    # Formants 8 % LOW (a big old chassis) - measured, Mayor and Stella were the cast's second-closest
    # pair (same centroid, same noisiness); with his down 8 % and hers up 18 % they now differ in
    # centroid as well as in f0 (122 vs 211 Hz) and pitch motion.
    y = _formants(src, seq, n, scale=0.92) + 0.15 * S.lowpass(src, 700.0)
    return y * _env(kind, n, 0.03, 0.06)


