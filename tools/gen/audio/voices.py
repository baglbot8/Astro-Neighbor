def v_bolt(kind, n, rng):
    """Data modem. Continuous-phase FSK: the carrier STEPS between four fixed tones on an even clock,
    with a 7 ms raised-cosine slide between steps (no gaps, no clicks) and a 25 ms handshake chirp up
    into the first tone. Literal and precise: no vibrato, no glide inside a step. A question ends with
    the last step sliding up 5 semitones; '!' is the two highest tones; '...' walks down and slows.

    TWO steps per gesture, never more, each >= 150 ms (PACE 1.4). Round 1 had 3-5 steps on a ~72 ms
    clock - the old per-letter blip interval was ~75 ms, so chained legato Bolt measured AS MANY onsets
    a second as the babble it replaced. The modem is now a slow two-tone handshake ("dee-daa")."""
    pat = {"short": ([1, 2], [1, 1]), "long": ([0, 3], [1, 1.15]),
           "ask": ([1, 3], [1, 1.1]), "exclaim": ([2, 3], [1, 1.1]),
           "trail": ([3, 0], [1, 1.35])}[kind]
    idx, w = pat
    w = np.array(w) / np.sum(w)
    bounds = _segments(n, np.concatenate([[0.0], np.cumsum(w)[:-1]]))
    semis = np.zeros(n)
    for k, ti in enumerate(idx):
        semis[bounds[k]:bounds[k + 1]] = 12.0 * math.log2(BOLT_TONES[ti] / 880.0)
    slide = S.n_samples(0.007)
    ker = np.hanning(2 * slide + 1)
    semis = np.convolve(np.pad(semis, slide, mode="edge"), ker / ker.sum(), mode="valid")
    t = S.times(n)
    # The question: the (already higher) last step lifts 2 semitones over its final 40 %. Round 1 slid
    # 5 semitones across the whole step, which the calibrated onset detector read as 3 extra syllables.
    if kind == "ask":
        last = bounds[-2]
        u = np.clip((np.arange(n - last) / max(n - last, 1) - 0.6) / 0.4, 0.0, 1.0)
        semis[last:] += 2.0 * (0.5 - 0.5 * np.cos(math.pi * u))
    # Handshake chirp up into the first tone: 0.75 -> 1 (5 semitones) in ~40 ms. At 0.6 -> 1 (9 st)
    # it counted as a syllable of its own on the high "!" gesture.
    f = 880.0 * 2.0 ** (semis / 12.0) * (1.0 - 0.25 * np.exp(-t / 0.012))
    y = S.lowpass(S.pulse(f, n, 0.5), 2000.0) * 0.8 + 0.35 * np.sin(_phase(f))
    clock = np.ones(n)
    for b in bounds[1:-1]:                                   # a small dip marks each clock edge
        a0, a1 = max(0, b - S.n_samples(0.004)), min(n, b + S.n_samples(0.004))
        clock[a0:a1] = 0.82
    return y * clock * _env(kind, n, 0.008, 0.03)


