def v_fen(kind, n, rng):
    """Bubbles. Sparse bubble resonances - each a sine whose pitch RISES 60 % in 30 ms as it nears the
    surface (how a real bubble sounds) and dies in 40-100 ms - over a faint wet gurgle. Irregular
    timing (+-8 ms seeded jitter), low for a bubble, slow and patient: Fen's gestures are the longest in
    the cast and have the fewest events in them - ONE bubble for a short phrase, TWO for the rest
    (round 1 had up to four, 3-4 onsets inside 0.4 s, which read as a gargle-babble)."""
    plan = {"short": [(0.0, 0, 0.07)],
            "long": [(0.0, 0, 0.06), (0.45, -3, 0.08)],
            "ask": [(0.0, 0, 0.05), (0.45, 5, 0.09)],
            "exclaim": [(0.0, 4, 0.05), (0.45, 7, 0.05)],
            "trail": [(0.0, 0, 0.07), (0.45, -5, 0.11)]}[kind]
    y = np.zeros(n)
    for k, (frac, semis, tau) in enumerate(plan):
        s0 = max(0, int(frac * n) + (S.n_samples(float(rng.uniform(-0.008, 0.008))) if k else 0))
        m = n - s0
        t = S.times(m)
        rise = 1.0 if (kind == "ask" and k == len(plan) - 1) else 0.6
        f = 390.0 * 2.0 ** (semis / 12.0) * (1.0 + rise * (1.0 - np.exp(-t / 0.03)))
        b = np.sin(_phase(f)) * np.exp(-t / tau) * np.clip(t / 0.002, 0, 1)
        y[s0:] += b
    gurgle = S.lowpass(S.noise(n, int(rng.integers(1 << 30))), 500.0) * 0.5
    gurgle *= 0.8 + 0.2 * np.sin(TWO_PI * 5.0 * S.times(n))   # 0.4 depth in round 1: a 5 Hz pulse of its own
    return (y + gurgle) * _env(kind, n, 0.01, 0.05)


