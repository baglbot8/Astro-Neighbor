def v_stella(kind, n, rng):
    """Human-ish radio murmur. A glottal-style source (saw tilted -12 dB/oct) plus breath noise gated by
    the glottal cycle, through formants that move about 3.5 times a second - a voice heard through a
    bad radio, unintelligible on purpose. Opposite of Mayor Orbit on every axis: organic not buzzy,
    205 Hz not 118, pitch swoops 1.5x the contour instead of stepping, vowels move fast not slow."""
    t = S.times(n)
    walk = np.cumsum(rng.normal(0.0, 1.0, n))
    walk = S.lowpass(walk - walk.mean(), 6.0)
    walk = walk / (np.max(np.abs(walk)) + 1e-9) * 0.006                  # ~0.6 % jitter
    f = 205.0 * _pitch(kind, n, 1.8) * (1.0 + walk)
    ph = _phase(f)
    saw = S.saw(f, n)
    glottal = S.onepole_lp(S.onepole_lp(saw, 900.0), 900.0) * 6.0
    # Breath is her signature against Mayor Orbit (who has none): 0.8, up from 0.45 in the first build,
    # where the two looked alike on a spectrogram - both a harmonic stack through formants.
    breath = S.bandpass(S.noise(n, int(rng.integers(1 << 30))), 2000.0, 0.7) * (0.5 + 0.5 * np.cos(ph)) * 0.8
    seq = {"short": [(0.0, "e"), (0.45, "a"), (1.0, "er")],
           "long": [(0.0, "a"), (0.28, "i"), (0.6, "o"), (1.0, "er")],
           "ask": [(0.0, "er"), (0.35, "a"), (1.0, "i")],
           "exclaim": [(0.0, "a"), (0.3, "e"), (1.0, "a")],
           "trail": [(0.0, "o"), (0.4, "a"), (1.0, "u")]}[kind]
    y = _formants(glottal + breath, seq, n, qs=(5.0, 7.0, 9.0), weights=(1.0, 0.7, 0.35), scale=1.18)
    y += 0.25 * _formants(breath, seq, n, qs=(3.0, 4.0, 5.0), weights=(0.3, 0.6, 0.6), scale=1.18)
    return y * _env(kind, n, 0.025, 0.06)


def _chirps(n, seq, base, up, sweep, floor, dyad=0.0):
    """Connected chirp segments on ONE continuous-phase oscillator (no re-attack between them).
    seq = [(start_frac, semis[, up]), ...]; each segment sweeps `sweep` semitones up or down (a third
    element overrides `up` for that segment - Pop's question turns upward on its last one)."""
    starts = [s[0] for s in seq]
    bounds = _segments(n, starts)
    semis = np.zeros(n)
    amp = np.full(n, floor)
    for k, item in enumerate(seq):
        st = item[1]
        seg_up = item[2] if len(item) > 2 else up
        a, b = bounds[k], bounds[k + 1]
        m = b - a
        u = np.arange(m) / max(m, 1)
        ease = 1.0 - (1.0 - np.clip(u / 0.6, 0, 1)) ** 2
        semis[a:b] = st + (ease * sweep - sweep * 0.7 if seg_up else (1.0 - ease) * sweep - sweep * 0.3)
        bump = np.sin(math.pi * np.clip(u, 0, 1)) ** 1.2
        amp[a:b] = np.maximum(floor, bump)
    f = base * 2.0 ** (semis / 12.0)
    ph = _phase(f)
    y = np.sin(ph)
    if dyad:
        y = y + dyad * np.sin(1.5 * ph + 0.7)
    return y, amp, ph


