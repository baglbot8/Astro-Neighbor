def v_pip(kind, n, rng):
    """Up-chirps. ONE sine (one antenna) that sweeps UP 7 semitones per chirp: ONE chirp for a short
    phrase or '!', TWO ('wheep-wheep', joined on a continuous oscillator) for the rest - never more.
    Round 1 had 2-4 chirps per gesture at 8-16 onsets a second, which chained legato was babble again.
    The brighter, faster, higher half of the twins."""
    seq = {"short": [(0.0, 0)], "long": [(0.0, 0), (0.5, 4)],
           "ask": [(0.0, 0), (0.5, 5)], "exclaim": [(0.0, 5)],
           "trail": [(0.0, 2), (0.5, -2)]}[kind]
    # No chirp starts above +5: its sweep tops out 2.1 semitones higher (1.7 kHz). At +9 round 1's
    # fundamental reached 1.9 kHz and 28 % of its energy sat above 2 kHz, the band the ear is most
    # sensitive to and the one that tires it. "!" is carried by the +1.5 dB trim and the high start.
    # 5-semitone sweeps, and the level only dips to 0.5 between the two chirps (one breath, two
    # inflections). Measured on the demo with three onset detectors calibrated on the old blips: 7 st over
    # a 0.3 floor (round 1) and 4 st over a 0.12 floor both read 3 onsets per two-chirp gesture - a deep
    # dip makes each chirp re-attack - while 5 st over 0.5 is 0.31 / 0.25 / 0.23 of the old rate.
    y, amp, ph = _chirps(n, seq, 1150.0, True, 5.0, 0.5)
    y = y + 0.18 * np.sin(2.0 * ph)
    return y * amp * _env(kind, n, 0.006, 0.03)


