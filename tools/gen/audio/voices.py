def v_pop(kind, n, rng):
    """Down-chirps. A DYAD - two sines a perfect fifth apart (two antennae, double the listening) - that
    sweep DOWN 6 semitones per segment with a rounder 'bop'. Same chirp machinery as Pip so the twins
    read as family; opposite direction, a fifth lower, slower segments and no harmonics so they never
    read as the same voice. Pop's question is the one segment that sweeps up. Like Pip: one 'bop' for
    a short phrase or '!', two for the rest, never more (round 1 had up to four)."""
    seq = {"short": [(0.0, 0)], "long": [(0.0, 2), (0.5, -1)],
           "ask": [(0.0, 0), (0.5, 3, True)], "exclaim": [(0.0, 6)],
           "trail": [(0.0, 1), (0.5, -4)]}[kind]
    # 3-semitone sweeps over a 0.6 floor. Swept on the demo (flux / SuperFlux / envelope detectors, each
    # calibrated on the old blips): 6 st over 0.35 (round 1) = 0.65 / 0.45 / 0.65 of the old rate;
    # 3.5 st over 0.12 = 0.70 / 0.40 / 0.35; 3 st over 0.6 = 0.40 / 0.30 / 0.29. Still Pop's shape - a
    # rounder, lower, DOWNWARD dyad against Pip's single rising sine - just one breath, not four blips.
    y, amp, _ = _chirps(n, seq, 780.0, False, 3.0, 0.6, dyad=0.55)
    return S.lowpass(y * amp, 2400.0) * _env(kind, n, 0.01, 0.04)


