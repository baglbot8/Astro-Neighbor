# =========================================================================================== the radio
def _click(n, seed):
    """Relay click: a 3-sample impulse ringing a 1.9 kHz resonance, and a 520 Hz 'thunk' under it."""
    t = S.times(n)
    imp = np.zeros(n)
    imp[1:4] = [1.0, -0.7, 0.25]
    ring = S.svf_tv(imp, 1900.0, 3.0, "bp") * 6.0
    thunk = np.sin(TWO_PI * 520.0 * t) * np.exp(-t / 0.006) * 0.5
    return ring + thunk


def comms_key_up(variant):
    """KEY-UP: click, then a ~90 ms burst of band-limited static that opens the line."""
    rng = np.random.default_rng(900 + variant)
    n = S.n_samples(0.15)
    t = S.times(n)
    hold = (0.045, 0.07)[variant]
    burst = S.bandpass(S.pink_noise(n, 910 + variant), 1300.0, 0.7)   # 1.3 kHz: it plays on EVERY line,
                                                                      # so it is kept below the ear's 2-5 kHz peak
    crack = (rng.uniform(0, 1, n) < 0.004) * rng.uniform(-1, 1, n) * 3.0
    burst = burst / (S.peak(burst) + 1e-9) + S.bandpass(crack, 1800.0, 1.5)
    env = np.clip((t - 0.006) / 0.003, 0, 1) * np.where(t < hold, 1.0, np.exp(-(t - hold) / 0.03))
    y = _click(n, variant) * 0.9 + burst * env * 0.55
    return y * S.env_perc(n, 10.0, 0.0005, end_fade=0.02)


def _squelch(n, hold, seed):
    rng = np.random.default_rng(seed)
    t = S.times(n)
    hiss = S.bandpass(S.pink_noise(n, seed), 1600.0, 0.8)     # 1.6 kHz pink, not 2.1 kHz white: 40 % of the
                                                             # first build's energy sat above 2 kHz
    hiss = hiss / (S.peak(hiss) + 1e-9)
    crack = S.bandpass((rng.uniform(0, 1, n) < 0.006) * rng.uniform(-1, 1, n) * 2.5, 1500.0, 1.2)
    env = np.clip(t / 0.002, 0, 1) * np.exp(-t / 0.07) * np.clip((hold - t) / 0.004, 0, 1)
    close = np.zeros(n)
    c = min(n - 4, S.n_samples(hold))
    close[c:c + 3] = [0.5, -0.35, 0.1]
    drop = np.sin(TWO_PI * 300.0 * t) * np.exp(-t / 0.01) * 0.3
    return (hiss + crack) * env + S.svf_tv(close, 1700.0, 3.0, "bp") * 3.0 + drop


def comms_key_down(variant):
    """KEY-DOWN: the squelch tail - a hiss that snaps open as the carrier drops and gates shut."""
    return _squelch(S.n_samples(0.2), (0.14, 0.12)[variant], 930 + variant)


def comms_over():
    """OVER: a soft two-tone roger beep (E6 then B5, falling a fourth) and then the squelch. Plays only
    on the LAST line of a turn, so a conversation has a rhythm: key-up ... squelch, key-up ... 'over'."""
    n = S.n_samples(0.34)
    y = np.zeros(n)
    for f, a, d in ((1318.5, 0.0, 0.05), (987.8, 0.062, 0.07)):
        m = S.n_samples(d)
        tt = S.times(m)
        env = np.minimum(np.clip(tt / 0.005, 0, 1), np.clip((d - tt) / 0.008, 0, 1))
        tone = (np.sin(TWO_PI * f * tt) + 0.1 * np.sin(TWO_PI * 3 * f * tt)) * env * 0.55
        S.mix_into(y, tone, S.n_samples(a))
    S.mix_into(y, _squelch(S.n_samples(0.19), 0.13, 950) * 0.85, S.n_samples(0.15))
    return y


BED_LEN = 4 * S.QOA_FRAME          # 20480 samples at 22.05 kHz = 0.929 s, whole QOA frames


def comms_bed():
    """The static bed under an open line: pink-tilted noise band-limited to the channel, a 3.2 Hz
    flutter and a few crackles. Built directly at COMMS_RATE and filtered CIRCULARLY in one FFT, so the
    loop is exactly periodic - no seam at all, not just a small one."""
    rng = np.random.default_rng(970)
    L = BED_LEN
    w = rng.uniform(-1.0, 1.0, L)
    crack = (rng.uniform(0, 1, L) < 0.0012) * rng.uniform(-1, 1, L) * 6.0
    X = np.fft.rfft(w + crack)
    f = np.fft.rfftfreq(L, 1.0 / RATE)
    f[0] = 1.0
    pink = 1.0 / np.sqrt(f / 300.0)
    hp = (f / S.COMMS_LO) ** 4 / (1.0 + (f / S.COMMS_LO) ** 4)       # 24 dB/oct magnitude
    lp = 1.0 / (1.0 + (f / S.COMMS_HI) ** 4)
    X *= pink * hp * lp
    X[0] = 0.0
    y = np.fft.irfft(X, L)
    y /= np.max(np.abs(y)) + 1e-9
    k = np.arange(L)
    y *= 1.0 + 0.15 * np.sin(TWO_PI * 3.0 * k / L)                 # 3 whole cycles per loop
    return np.tanh(1.4 * y) / math.tanh(1.4)


# =========================================================================================== rendering
def _finish(y, lufs=None, peak_db=PEAK_CEIL_DB, drive=1.7):
    """Shared chain -> 22.05 kHz -> level. With `lufs`, normalise loudness then cap the peak."""
    y = S.comms_chain(y, drive=drive)
    y = S.fade_edges(y, 0.002, 0.006)
    y = S.remove_dc(y)
    if lufs is not None:
        y = y * S.db(lufs - S.loudness_k(y))
        if S.peak(y) > S.db(peak_db):
            y = S.normalize(y, peak_db)
    else:
        y = S.normalize(y, peak_db)
    return S.resample_half(y)


def comms_names():
    names = ["voice_%s_%s" % (v, k) for v in CAST for k in KINDS]
    return names + ["comms_key_up_0", "comms_key_up_1", "comms_key_down_0", "comms_key_down_1",
                    "comms_over", "comms_bed"]


def comms_render(name):
    """-> (mono float at RATE, loop?)"""
    if name == "comms_bed":
        return S.normalize(comms_bed(), PEAK_CEIL_DB), True
    if name.startswith("comms_key_up_"):
        return _finish(comms_key_up(int(name[-1])), lufs=RADIO_LUFS["key_up"], drive=1.3), False
    if name.startswith("comms_key_down_"):
        return _finish(comms_key_down(int(name[-1])), lufs=RADIO_LUFS["key_down"], drive=1.3), False
    if name == "comms_over":
        return _finish(comms_over(), lufs=RADIO_LUFS["over"], drive=1.3), False
    _, voice, kind = name.split("_", 1)[0], *name[len("voice_"):].rsplit("_", 1)
    seed = 1000 + list(CAST).index(voice) * 10 + KINDS.index(kind)
    rng = np.random.default_rng(seed)
    y = VOICE_GEN[voice](kind, _n(voice, kind), rng)
    return _finish(y, lufs=GESTURE_LUFS + KIND_TRIM_DB.get(kind, 0.0)), False


def analyse(x, rate=RATE):
    """Numbers for one file: seconds, peak/RMS dBFS, K-loudness, centroid, 90 % bandwidth, and how much
    energy sits inside the 300-3400 Hz channel and above 2 kHz (the fatiguing region)."""
    m = S.to_mono(x)
    up = S.upsample_double(m) if rate == RATE else m
    spec = np.abs(np.fft.rfft(up * np.hanning(len(up)))) ** 2
    f = np.fft.rfftfreq(len(up), 1.0 / S.SR)
    tot = spec.sum() + 1e-12
    cen = float((spec * f).sum() / tot)
    cum = np.cumsum(spec) / tot
    lo, hi = f[np.searchsorted(cum, 0.05)], f[np.searchsorted(cum, 0.95)]
    return {"sec": len(m) / rate, "peak": S.to_db(S.peak(m)), "rms": S.to_db(S.rms(m)),
            "lufs": S.loudness_k(up), "centroid": cen, "bw90": (lo, hi),
            "in_band": float(spec[(f >= 300) & (f <= 3400)].sum() / tot),
            "above_2k": float(spec[f > 2000].sum() / tot)}


def build(write=True):
    rows = []
    total = 0
    for name in comms_names():
        x, loop = comms_render(name)
        path = os.path.join(SFX_DIR, name + ".wav")
        size = S.write_wav(path, x, loop=loop, rate=RATE) if write else len(x) * 2 + 44
        total += size
        a = analyse(x)
        rows.append((name, a, size, loop))
        print("%-24s %5.3fs pk %6.2f rms %6.2f lufs %6.2f cen %5d bw %4d-%4d in %.3f >2k %.3f %5.1f KB%s" % (
            name, a["sec"], a["peak"], a["rms"], a["lufs"], a["centroid"], a["bw90"][0], a["bw90"][1],
            a["in_band"], a["above_2k"], size / 1024.0, "  LOOP" if loop else ""))
    print("comms set: %d files, %.1f KB" % (len(rows), total / 1024.0))
    return rows


# =========================================================================================== scheduler mirror
PUNCT = ".!?,;:—…"


def parse_phrases(line):
    """Split a line into phrases - MIRRORS AudioManager._comms_parse(). Returns
    [{"start": char index where the phrase's first letter is revealed, "letters": n, "kind": str}].
    kind: ask (?), exclaim (!), trail (... or the ellipsis char), go (, ; : dash), say (. or nothing).
    A phrase ends at a run of PUNCT followed by whitespace or the end of the line; a run at the START of
    a phrase ("...and that's our shop!") is leading, not terminal."""
    out = []
    i, n = 0, len(line)
    while i < n:
        while i < n and line[i] in " \n\t":
            i += 1
        if i >= n:
            break
        start = i
        letters = 0
        while i < n:
            c = line[i]
            if c in PUNCT and letters > 0:
                j = i
                while j < n and line[j] in PUNCT:
                    j += 1
                if j >= n or line[j] in " \n\t":
                    run = line[i:j]
                    kind = "say"
                    if "?" in run:
                        kind = "ask"
                    elif "!" in run:
                        kind = "exclaim"
                    elif run.endswith("...") or "…" in run:
                        kind = "trail"
                    elif any(ch in run for ch in ",;:—"):
                        kind = "go"
                    out.append({"start": start, "end": j, "letters": letters, "kind": kind})
                    i = j
                    break
                i = j
                continue
            if c.isalnum():
                letters += 1
            i += 1
        else:
            if letters > 0:
                out.append({"start": start, "end": n, "letters": letters, "kind": "say"})
    # one extra gesture for a long phrase, at the word break nearest its middle
    split = []
    for p in out:
        if p["letters"] > SPLIT_PHRASE_CHARS:
            mid = (p["start"] + p["end"]) // 2
            spaces = [k for k in range(p["start"] + 1, p["end"] - 1) if line[k] == " "]
            if spaces:
                k = min(spaces, key=lambda s: abs(s - mid)) + 1
                first = sum(1 for c in line[p["start"]:k] if c.isalnum())
                split.append({"start": p["start"], "end": k, "letters": first, "kind": "go"})
                split.append({"start": k, "end": p["end"], "letters": p["letters"] - first, "kind": p["kind"]})
                continue
        split.append(p)
    return split


def gesture_file(voice, phrase):
    kind = phrase["kind"]
    if kind in ("ask", "exclaim", "trail"):
        return "voice_%s_%s" % (voice, kind)
    return "voice_%s_%s" % (voice, "short" if phrase["letters"] <= SHORT_PHRASE_CHARS else "long")


def gesture_pitch(phrase, k, count, rng):
    """pitch_scale for the k-th of `count` phrases - MIRRORS AudioManager._comms_play_phrase()."""
    decl = DECLINATION * (1.0 - 2.0 * k / max(1, count - 1)) if count > 1 else 0.0
    go = GO_PITCH if phrase["kind"] == "go" else 0.0
    return 1.0 + decl + go + rng.uniform(-JITTER, JITTER)


def file_seconds(name):
    x, rate, _ = S.read_wav(os.path.join(SFX_DIR, name + ".wav"))
    return S.length(x) / rate


def _enqueue(queue, k):
    """MIRRORS AudioManager._comms_enqueue: keep the FIRST phrase and the NEWEST; drop middle ones."""
    if queue and queue[-1] != 0:
        queue[-1] = k
    else:
        queue.append(k)


def schedule_line(voice, line, closes_turn, t0, rng, lengths, flushed=False):
    """Event list for one line exactly as the game schedules it: the typewriter reveals int(t*CPS)
    characters per 1/FPS frame (from t0); a phrase becomes due on the frame its first letter shows; a
    due gesture plays as soon as the voice is free, PHRASE_GAP after the previous one ends. While the
    voice is busy only the line's first phrase and its newest due phrase wait (middle ones are dropped),
    so neither the opener ("Oh!") nor the prosody-carrying last phrase is ever lost. The key-down waits
    for the voice to finish. `flushed` = the previous line's squelch was flushed at t0, so the key-up
    comes FLUSH_GAP later. Returns (events [(t, name, pitch_scale, volume_db)], t_line_complete)."""
    lead = FLUSH_GAP if flushed else 0.0
    ev = [(t0 + lead, "comms_key_up_%d" % (rng.integers(2)), 1.0, RADIO_DB)]
    phrases = parse_phrases(line)
    free_at = t0 + lead + KEYUP_LEAD
    nxt, queue = 0, []
    total = len(line)
    frame = 0
    typed = 0.0
    visible = 0
    done = t0
    while True:
        frame += 1
        now = t0 + frame / FPS
        typed += CPS / FPS
        visible = min(int(typed), total)
        while nxt < len(phrases) and phrases[nxt]["start"] < visible:
            _enqueue(queue, nxt)
            nxt += 1
        if queue and now >= free_at:
            k = queue.pop(0)
            p = phrases[k]
            name = gesture_file(voice, p)
            ps = gesture_pitch(p, k, len(phrases), rng)
            ev.append((now, name, ps, VOICE_DB))
            free_at = now + lengths[name] / ps + PHRASE_GAP
        if visible >= total:
            done = now
            break
    at = max(done, free_at)               # phrases still waiting for the voice play back to back
    for k in queue:
        p = phrases[k]
        name = gesture_file(voice, p)
        ps = gesture_pitch(p, k, len(phrases), rng)
        ev.append((at, name, ps, VOICE_DB))
        at += lengths[name] / ps + PHRASE_GAP
    t_kd = max(done, at - PHRASE_GAP) + TAIL_GAP
    ev.append((t_kd, "comms_over" if closes_turn else "comms_key_down_%d" % (rng.integers(2)), 1.0, RADIO_DB))
    return ev, done


