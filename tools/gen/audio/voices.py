def v_vela(kind, n, rng):
    """Glass. Free-bar partials (1 : 2.76 : 5.40, inharmonic, so 'glass', never Nova's harmonic FM) with a
    soft 25 ms rubbed attack instead of a strike - formal and warm - each partial doubled 1.5 cents sharp
    for a slow shimmer. Notes overlap and ring into each other; a courteous falling fourth is her
    statement, a rising sixth her question."""
    # One bell for a short phrase or '!', two for the rest, >= 165 ms apart (round 1: up to three, and
    # its short/exclaim pairs were 92-109 ms apart - a 9-11/s rate inside the gesture).
    notes = {"short": [(0.0, 0)], "long": [(0.0, 4), (0.45, -1)],
             "ask": [(0.0, 0), (0.45, 5)], "exclaim": [(0.0, 9)],
             "trail": [(0.0, 4), (0.45, -5)]}[kind]
    y = np.zeros(n)
    stretch = 1.6 if kind == "trail" else 1.0
    for frac, semis in notes:
        s0 = int(frac * n)
        m = n - s0
        t = S.times(m)
        f0 = 880.0 * 2.0 ** (semis / 12.0)
        note = np.zeros(m)
        for ratio, gain, tau in GLASS:
            g = gain * (1.5 if (kind == "exclaim" and ratio > 2) else 1.0)
            for det in (0.0, 1.5):
                f = f0 * ratio * 2.0 ** (det / 1200.0)
                note += g * (1.0 if det == 0.0 else 0.5) * np.sin(TWO_PI * f * t) * np.exp(-t / (tau * stretch))
        rub = 0.5 - 0.5 * np.cos(math.pi * np.clip(t / 0.025, 0.0, 1.0))    # every note swells in
        y[s0:] += note * rub
    return y * _env(kind, n, 0.025, 0.05)


