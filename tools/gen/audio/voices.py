# =========================================================================================== helpers
def _path(points, n):
    """[(t_fraction, value), ...] -> per-sample array, cosine-eased between points."""
    t = np.linspace(0.0, 1.0, n, endpoint=False)
    xs = np.array([p[0] for p in points], dtype=np.float64)
    ys = np.array([p[1] for p in points], dtype=np.float64)
    i = np.clip(np.searchsorted(xs, t, side="right") - 1, 0, len(xs) - 2)
    k = np.clip((t - xs[i]) / np.maximum(xs[i + 1] - xs[i], 1e-9), 0.0, 1.0)
    k = 0.5 - 0.5 * np.cos(math.pi * k)
    return ys[i] + (ys[i + 1] - ys[i]) * k


# Pitch contour per gesture kind, in semitones against the voice's own centre. A statement rises a
# little then falls; a question dips then climbs 4 semitones; "!" starts high; "..." sinks 4.5.
CONTOUR = {
    "short": [(0.0, -0.5), (0.35, 0.5), (1.0, -1.2)],
    "long": [(0.0, -0.7), (0.3, 0.8), (0.65, 0.0), (1.0, -1.8)],
    "ask": [(0.0, -0.3), (0.45, -1.0), (1.0, 4.0)],
    "exclaim": [(0.0, 2.2), (0.18, 3.4), (1.0, 0.4)],
    "trail": [(0.0, 0.0), (0.4, -1.0), (1.0, -4.5)],
}


def _pitch(kind, n, depth=1.0):
    return 2.0 ** (depth * _path(CONTOUR[kind], n) / 12.0)


def _env(kind, n, attack=0.02, release=0.05):
    """Raised-cosine attack/release, plus the kind's own shape (an accent for '!', a fade for '...')."""
    t = S.times(n)
    dur = n / S.SR
    a = 0.5 - 0.5 * np.cos(math.pi * np.clip(t / max(attack, 1e-4), 0.0, 1.0))
    r = 0.5 - 0.5 * np.cos(math.pi * np.clip((dur - t) / max(release, 1e-4), 0.0, 1.0))
    e = np.minimum(a, r)
    if kind == "trail":
        e = e * _path([(0.0, 1.0), (0.35, 0.9), (1.0, 0.18)], n)
    elif kind == "exclaim":
        e = e * _path([(0.0, 1.0), (0.25, 1.0), (1.0, 0.72)], n)
    return e


def _phase(f):
    """Per-sample frequency -> running phase in radians (continuous, so glides never click)."""
    return TWO_PI * np.cumsum(np.asarray(f, dtype=np.float64)) / S.SR


def _n(voice, kind):
    return S.n_samples(DUR[kind] * PACE.get(voice, 1.0))


def _segments(n, fracs):
    """Sample offsets for segment start fractions (the last segment runs to n)."""
    return [int(round(f * n)) for f in fracs] + [n]


