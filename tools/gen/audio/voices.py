def v_zorp(kind, n, rng):
    """Theremin. One pure sine that never re-attacks: it glides legato through the contour, finds each
    note with a 30 ms scoop from 3 semitones below (a thereminist 'finding' the pitch), and wears a wide
    vibrato that grows through the gesture. Earnest and curious - the whole gesture is one breath."""
    t = S.times(n)
    dur = n / S.SR
    # Contour at 1.2x (round 1: 1.6x) and a 1.5-semitone scoop (round 1: 3). A continuously gliding pitch
    # is what the plain spectral-flux onset detector counts as syllables: at 1.6x / 3 st Zorp's demo read
    # 0.54 of the old blip rate, at 1.2x / 1.5 st 0.42 (SuperFlux 0.23, envelope 0.18). Still a glide.
    scoop = 2.0 ** (-1.5 * np.exp(-t / 0.03) / 12.0)
    pitch = _pitch(kind, n, 1.2) * scoop
    # Vibrato 5 Hz, 16-26 cents, fading in over 150 ms; no volume wobble. Round 1 ran 6.3 Hz at 30-48
    # cents with an 8 % volume wobble on the same beat, and an onset detector calibrated on the old blips
    # counted every vibrato up-swing as a new syllable: 4 "onsets" per gesture, 0.58x the old babble
    # rate. The glide and the scoop are what make it a theremin; the vibrato only has to shimmer.
    rate = 5.0 if kind != "trail" else 5.0 - 1.2 * (t / dur)
    depth = np.clip(t / 0.15, 0.0, 1.0) * (16.0 + 10.0 * (t / dur))      # cents
    vib = 2.0 ** (depth * np.sin(TWO_PI * np.cumsum(np.full(n, 1.0) * rate) / S.SR) / 1200.0)
    f = 590.0 * pitch * vib
    ph = _phase(f)
    bright = 0.25 if kind == "exclaim" else 0.14
    y = np.sin(ph) + bright * np.sin(2.0 * ph + 0.3) + 0.05 * np.sin(3.0 * ph)
    return y * _env(kind, n, 0.035, 0.06)


