def v_grig(kind, n, rng):
    """Gravel. An 84 Hz narrow-pulse growl - its fundamental is below the channel, so it arrives as a low
    buzz through its harmonics and one fixed "uh" resonance - with SPARSE crackle grains on top (~90 a
    second, each a distinct crunch through 750 Hz / 1.2 kHz stone resonances). Three earlier balances
    failed: growl alone read as a lower Mayor Orbit (a dense harmonic stack); dense grains (440/s) plus a
    noise bed read as the radio's own static; and 180 grains/s at 0.9 still measured harmonicity 0.10 and
    looked like the key-up burst on the spectrogram - interference, not a voice. Blunt:
    an 8 ms attack, the contour at 0.6 depth, a flat top. (A 31 Hz roughness from the first build is
    gone: roughness at 20-50 Hz is a known listening-fatigue source.)"""
    t = S.times(n)
    lift = 1.18 if kind == "exclaim" else 1.0
    f = 84.0 * lift * _pitch(kind, n, 0.6)
    pulse = S.pulse(f, n, 0.22)
    # Round 2: the growl carries the voice. Round 1's mix (crackle 0.9, rumble 0.3) measured harmonicity
    # 0.10 - the flattest spectrum in the cast - and on the spectrogram looked like the key-up / squelch
    # static, i.e. interference rather than somebody talking. The growl now goes through ONE FIXED low
    # "uh" resonance (520 Hz + a weaker 1.05 kHz) - fixed, so it never glides between vowels the way
    # Mayor Orbit's vocoder does - and the crackle is sparse seasoning (90 grains/s at half the gain).
    growl = S.lowpass(pulse, 1100.0) * 0.5 + S.svf_tv(pulse, np.full(n, 520.0), 4.0, "bp") * 1.6 \
        + S.svf_tv(pulse, np.full(n, 1050.0), 5.0, "bp") * 0.6
    # Constant density: round 1 thinned the trail's grains toward the end, and isolated grains in a
    # fading gesture each read as a separate click (5 detected onsets on voice_grig_trail).
    rate = {"exclaim": 130.0, "trail": 70.0}.get(kind, 90.0)
    dens = np.full(n, rate / S.SR)
    grains = (rng.uniform(0.0, 1.0, n) < dens) * rng.uniform(0.5, 1.0, n) * np.sign(rng.uniform(-1, 1, n))
    crackle = S.bandpass(grains, 750.0, 1.4) * 4.0 + S.bandpass(grains, 1200.0, 1.8) * 1.5
    rumble = S.bandpass(S.noise(n, int(rng.integers(1 << 30))), 450.0, 0.9)
    rumble *= 0.7 + 0.3 * np.sin(TWO_PI * 6.0 * t + 1.0)
    y = 1.0 * growl + 0.45 * crackle + 0.1 * rumble
    if kind == "long":
        y *= _path([(0.0, 1.0), (0.42, 1.0), (0.5, 0.35), (0.58, 1.0), (1.0, 1.0)], n)
    return y * _env(kind, n, 0.008, 0.04)


GLASS = [(1.0, 1.0, 0.36), (2.76, 0.42, 0.22), (5.40, 0.12, 0.14)]   # (ratio, gain, decay s)


